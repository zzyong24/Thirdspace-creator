import { z } from "zod";
import { defineEndpoint } from "../endpoints";
import {
  id,
  iso8601,
  paginationQuery,
  contentRole,
  productStatus,
  leadSource,
  leadStatus,
  attributionMethod,
  attributionConfidence,
  conversionEventType,
} from "../primitives";
import {
  productResource,
  offerResource,
  leadResource,
  conversionEventResource,
  contentOutputProductResource,
  funnelStageResource,
  monetizationFunnelResource,
} from "../resources/monetization";

const productParams = z.object({ productId: id });
const outputParams = z.object({ outputId: id });
const leadParams = z.object({ leadId: id });

// SPEC §13 "变现 (monetization)" group (七步⑦, contract v0.4).
export const monetizationOperations = {
  listProducts: defineEndpoint({
    id: "products.list",
    method: "GET",
    path: "/products",
    query: paginationQuery.extend({ status: productStatus.optional() }),
    response: productResource,
    isList: true,
    fr: ["FR-MON-PRODUCT-LIST"],
  }),
  createProduct: defineEndpoint({
    id: "products.create",
    method: "POST",
    path: "/products",
    body: z.object({
      name: z.string().min(1),
      kind: z.string().min(1),
      tier: z.string().optional(),
      deliveryWeight: z.string().optional(),
      targetPersona: z.string().optional(),
    }),
    response: productResource,
    fr: ["FR-MON-PRODUCT-CREATE"],
  }),
  getProduct: defineEndpoint({
    id: "products.get",
    method: "GET",
    path: "/products/:productId",
    params: productParams,
    response: productResource,
    fr: ["FR-MON-PRODUCT-GET"],
  }),
  patchProduct: defineEndpoint({
    id: "products.patch",
    method: "PATCH",
    path: "/products/:productId",
    params: productParams,
    body: z.object({
      name: z.string().optional(),
      kind: z.string().optional(),
      tier: z.string().optional(),
      deliveryWeight: z.string().optional(),
      targetPersona: z.string().optional(),
      status: productStatus.optional(),
    }),
    response: productResource,
    fr: ["FR-MON-PRODUCT-PATCH"],
  }),
  retireProduct: defineEndpoint({
    id: "products.retire",
    method: "POST",
    path: "/products/:productId/retire",
    params: productParams,
    response: productResource,
    fr: ["FR-MON-PRODUCT-RETIRE"],
  }),
  listOffers: defineEndpoint({
    id: "products.offers.list",
    method: "GET",
    path: "/products/:productId/offers",
    params: productParams,
    response: offerResource,
    isList: true,
    fr: ["FR-MON-OFFER-LIST"],
  }),
  createOffer: defineEndpoint({
    id: "products.offers.create",
    method: "POST",
    path: "/products/:productId/offers",
    params: productParams,
    body: z.object({
      price: z.number(),
      currency: z.string().optional(),
      validFrom: iso8601.optional(),
      validTo: iso8601.optional(),
      note: z.string().optional(),
    }),
    response: offerResource,
    fr: ["FR-MON-OFFER-CREATE"],
  }),
  listOutputProducts: defineEndpoint({
    id: "outputs.products.list",
    method: "GET",
    path: "/outputs/:outputId/products",
    params: outputParams,
    response: contentOutputProductResource,
    isList: true,
    fr: ["FR-MON-OUTPUT-PRODUCT-LIST"],
  }),
  linkOutputProduct: defineEndpoint({
    id: "outputs.products.link",
    method: "POST",
    path: "/outputs/:outputId/products",
    params: outputParams,
    body: z.object({ productId: id, contentRole: contentRole.optional() }),
    response: contentOutputProductResource,
    fr: ["FR-MON-OUTPUT-PRODUCT-LINK"],
  }),
  unlinkOutputProduct: defineEndpoint({
    id: "outputs.products.unlink",
    method: "DELETE",
    path: "/outputs/:outputId/products/:productId",
    params: z.object({ outputId: id, productId: id }),
    response: z.object({ ok: z.literal(true) }),
    fr: ["FR-MON-OUTPUT-PRODUCT-UNLINK"],
  }),
  listLeads: defineEndpoint({
    id: "leads.list",
    method: "GET",
    path: "/leads",
    query: paginationQuery.extend({
      status: leadStatus.optional(),
      source: leadSource.optional(),
    }),
    response: leadResource,
    isList: true,
    fr: ["FR-MON-LEAD-LIST"],
  }),
  createLead: defineEndpoint({
    id: "leads.create",
    method: "POST",
    path: "/leads",
    body: z.object({
      source: leadSource.default("manual"),
      surveySource: z.string().optional(),
      attributedContentId: id.optional(),
      attributionMethod: attributionMethod.optional(),
      attributionConfidence: attributionConfidence.optional(),
      status: leadStatus.optional(),
    }),
    response: leadResource,
    fr: ["FR-MON-LEAD-CREATE"],
  }),
  getLead: defineEndpoint({
    id: "leads.get",
    method: "GET",
    path: "/leads/:leadId",
    params: leadParams,
    response: leadResource,
    fr: ["FR-MON-LEAD-GET"],
  }),
  patchLead: defineEndpoint({
    id: "leads.patch",
    method: "PATCH",
    path: "/leads/:leadId",
    params: leadParams,
    body: z.object({
      status: leadStatus.optional(),
      attributedContentId: id.optional(),
      attributionMethod: attributionMethod.optional(),
      attributionConfidence: attributionConfidence.optional(),
    }),
    response: leadResource,
    fr: ["FR-MON-LEAD-PATCH"],
  }),
  listConversions: defineEndpoint({
    id: "leads.conversions.list",
    method: "GET",
    path: "/leads/:leadId/conversions",
    params: leadParams,
    response: conversionEventResource,
    isList: true,
    fr: ["FR-MON-CONVERSION-LIST"],
  }),
  createConversion: defineEndpoint({
    id: "leads.conversions.create",
    method: "POST",
    path: "/leads/:leadId/conversions",
    params: leadParams,
    body: z.object({
      productId: id.optional(),
      offerId: id.optional(),
      eventType: conversionEventType,
      value: z.number().optional(),
      occurredAt: iso8601.optional(),
    }),
    response: conversionEventResource,
    fr: ["FR-MON-CONVERSION-CREATE"],
  }),
  getFunnel: defineEndpoint({
    id: "monetization.funnel.get",
    method: "GET",
    path: "/monetization/funnel",
    query: z.object({
      productId: id.optional(),
      periodStart: iso8601.optional(),
      periodEnd: iso8601.optional(),
    }),
    response: monetizationFunnelResource,
    fr: ["FR-MON-FUNNEL-GET"],
  }),
  getFunnelByOutput: defineEndpoint({
    id: "monetization.funnel.byOutput",
    method: "GET",
    path: "/outputs/:outputId/funnel",
    params: outputParams,
    response: funnelStageResource,
    isList: true,
    fr: ["FR-MON-FUNNEL-BY-OUTPUT"],
  }),
} as const;
