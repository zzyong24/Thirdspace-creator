// SEMANTIC_BOUNDARY_ALLOW: 只按协议UTF8字节上限裁切附件，不解释/归类异常内容。
export function boundedExceptionContext<T extends ExceptionCapture>(
  event: T,
): T {
  const clip = (text: string, bytes: number) =>
    new TextDecoder().decode(new TextEncoder().encode(text).slice(0, bytes));
  const value = {
    ...event,
    stack: clip(event.stack, 16000),
    message: clip(event.message, 4000),
  };
  while (
    new TextEncoder().encode(JSON.stringify(value)).byteLength > 32768 &&
    value.stack.length > 0
  )
    value.stack = value.stack.slice(0, -256);
  return value;
}

