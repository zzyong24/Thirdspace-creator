function normalizePunctuation(value) {
  return value
    .replace(/([\u3400-\u9fff])\s*:\s*(?=[\u3400-\u9fff“"「])/g, "$1：")
    .replace(/([\u3400-\u9fff])\s*,\s*(?=[\u3400-\u9fff])/g, "$1，")
    .replace(/([\u3400-\u9fff])\?(?=\s|$)/gm, "$1？")
    .replace(/\bVS\b/g, "vs")
    .replace(/\bIP\s*([，。；：])/g, "IP$1")
    .replace(/[ \t]+\n/g, "\n");
}

