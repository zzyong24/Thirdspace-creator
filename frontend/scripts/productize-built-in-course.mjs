function applyKnowledgePointEditorial(raw) {
  return raw
    .split(/\n(?=- id: KP-)/)
    .map((block) => {
      const id = block.match(/^- id:\s*(\S+)/m)?.[1];
      const editorial = id ? KNOWLEDGE_POINT_EDITORIAL.get(id) : undefined;
      if (!editorial) return block;
      let next = block;
      if (editorial.title) {
        next = next.replace(/^  title:\s*.+$/m, `  title: ${editorial.title}`);
      }
      if (editorial.oneLine) {
        next = next.replace(/^  one_line:\s*.+$/m, `  one_line: ${editorial.oneLine}`);
      }
      return next;
    })
    .join("\n");
}

function extractKnowledgePointTitles(raw) {
  return [...raw.matchAll(/^  title:\s*(.+?)\s*$/gm)].map((match) => match[1]);
}

