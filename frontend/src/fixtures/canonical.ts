const SHANGHAI_OFFSET_MS = 8 * 60 * 60 * 1000;

function shanghai(year: number, month: number, day: number, hour = 0, minute = 0): string {
  // Construct in UTC then label with the Shanghai offset so the ISO string
  // reflects the Asia/Shanghai wall clock without depending on the host
  // timezone.
  const utcMillis = Date.UTC(year, month - 1, day, hour, minute) - SHANGHAI_OFFSET_MS;
  return new Date(utcMillis).toISOString();
}

