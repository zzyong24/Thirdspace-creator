import {afterAll,beforeAll,it,expect} from 'vitest';
import {createDb,assets,assetFiles,eq} from '@creatoros/backend';
import {createAccountGroupService} from '../platform-account/account-group.service';
import {createPendingGeneratedAssetService} from './pending-generated-asset.service';
import {createAssetProcessingService} from './asset-processing.service';
let store:Awaited<ReturnType<typeof createDb>>;
beforeAll(async()=>{store=await createDb();},180000);
afterAll(async()=>{await store?.client.close();},180000);
it('原组Codex生成图可按原文件处理，跨组与替换版本不能读写',async()=>{
 let seq=0;const deps={db:store.db,now:()=>new Date().toISOString(),nextId:(p:string)=>`${p}-${++seq}`};
 const base={userId:'codex-asset-owner',requestId:'original-processing',source:'user' as const};
 const groups=createAccountGroupService(deps);
 const a=(await groups.create(base,{name:'原组',idempotencyKey:'processing-a'})).id,b=(await groups.create(base,{name:'另一组',idempotencyKey:'processing-b'})).id;
 const files=new Map<string,Uint8Array>();
 const generated=createPendingGeneratedAssetService({...deps,authorize:async()=>{},objectStorageForCtx:async()=>({getObject:async(k:string)=>files.get(k)??null,putObject:async(v:any)=>{files.set(v.storageKey,v.bytes);},headObject:async(k:string)=>({fileSize:files.get(k)!.byteLength,mimeType:'image/png'})} as any)});
 const ctx={...base,groupId:a};
 const saved=await generated.submit(ctx,{operationKey:'native-original',assetType:'image',mimeType:'image/png',name:'原Codex图片',bytes:new Uint8Array([1,2,3])});
 const [asset]=await store.db.select().from(assets).where(eq(assets.id,saved.assetId));
 if(!asset)throw Error('真实原素材未建立');
 expect(asset.accountId).toBeNull();expect(asset.groupId).toBe(a);
 const target={taskType:'asset.classify' as const,assetId:asset.id,fileId:asset.currentFileId,checksum:null,fileName:asset.name,mimeType:'image/png',skipModel:false};
 const owner=createAssetProcessingService();
 await expect(store.db.transaction(tx=>owner.lock(tx as any,ctx,target))).resolves.toMatchObject({id:asset.id});
 await expect(store.db.transaction(tx=>owner.lock(tx as any,{...base,groupId:b},target))).rejects.toThrow('素材版本或归属已变化');
 await expect(store.db.transaction(tx=>owner.annotate(tx as any,ctx,{...target,fileId:'wrong-original-version'},{aiDescription:'不可保存'}))).rejects.toThrow('素材版本或归属已变化');
 await store.db.transaction(tx=>owner.annotate(tx as any,ctx,target,{aiDescription:'原图实际描述'}));
 const [file]=await store.db.select().from(assetFiles).where(eq(assetFiles.id,asset.currentFileId!));
 if(!file)throw Error('原文件未建立');
 expect(file.mediaMetadata).toMatchObject({aiDescription:'原图实际描述'});
});
